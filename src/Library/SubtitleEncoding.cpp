QString guess(const QByteArray &sample)
{
    if (sample.startsWith(QByteArray::fromHex("efbbbf"))) {
        return QStringLiteral("utf-8");
    }
    if (sample.startsWith(QByteArray::fromHex("fffe"))) {
        return QStringLiteral("utf-16le");
    }
    if (sample.startsWith(QByteArray::fromHex("feff"))) {
        return QStringLiteral("utf-16be");
    }
    if (looksLikeUtf8(sample)) {
        return QStringLiteral("utf-8");
    }

    qsizetype high = 0;
    qsizetype asciiLetters = 0;
    for (const char c : sample) {
        const unsigned char byte = static_cast<unsigned char>(c);
        if (byte >= 0x80) {
            ++high;
        } else if ((byte >= 'A' && byte <= 'Z') || (byte >= 'a' && byte <= 'z')) {
            ++asciiLetters;
        }
    }

    return high * 2 > asciiLetters ? QStringLiteral("cp1251")
                                   : QStringLiteral("cp1250");
}

QString decode(const QByteArray &bytes, const QString &encoding)
{
    if (encoding == QLatin1String("cp1250")) {
        return decodeSingleByte(bytes, kCp1250);
    }
    if (encoding == QLatin1String("cp1251")) {
        return decodeSingleByte(bytes, kCp1251);
    }
    if (encoding == QLatin1String("utf-16le")) {
        QStringDecoder decoder(QStringDecoder::Utf16LE);
        return decoder.decode(bytes);
    }
    if (encoding == QLatin1String("utf-16be")) {
        QStringDecoder decoder(QStringDecoder::Utf16BE);
        return decoder.decode(bytes);
    }
    return QString::fromUtf8(bytes);
}

