bool isContinuation(unsigned char byte)
{
    return (byte & 0xC0) == 0x80;
}

bool looksLikeUtf8(const QByteArray &sample)
{
    const qsizetype size = sample.size();
    qsizetype i = 0;
    while (i < size) {
        const unsigned char lead = static_cast<unsigned char>(sample.at(i));
        if (lead < 0x80) {
            ++i;
            continue;
        }

        qsizetype length = 0;
        if (lead >= 0xC2 && lead <= 0xDF) {
            length = 2;
        } else if (lead >= 0xE0 && lead <= 0xEF) {
            length = 3;
        } else if (lead >= 0xF0 && lead <= 0xF4) {
            length = 4;
        } else {
            return false;
        }

        const qsizetype available = qMin(length, size - i);
        for (qsizetype k = 1; k < available; ++k) {
            if (!isContinuation(static_cast<unsigned char>(sample.at(i + k)))) {
                return false;
            }
        }
        i += length;
    }
    return true;
}

QString decodeSingleByte(const QByteArray &bytes, const char16_t *table)
{
    QString text;
    text.reserve(bytes.size());
    for (const char c : bytes) {
        const unsigned char byte = static_cast<unsigned char>(c);
        text.append(byte < 0x80 ? QChar(byte) : QChar(table[byte - 0x80]));
    }
    return text;
}

